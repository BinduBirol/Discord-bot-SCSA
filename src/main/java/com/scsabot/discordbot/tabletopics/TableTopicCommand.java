package com.scsabot.discordbot.tabletopics;


import com.scsabot.discordbot.dto.TableTopicQuestion;
import com.scsabot.discordbot.dto.TableTopicSession;
import com.scsabot.discordbot.service.RoleService;
import lombok.RequiredArgsConstructor;
import net.dv8tion.jda.api.EmbedBuilder;
import net.dv8tion.jda.api.events.interaction.command.SlashCommandInteractionEvent;
import org.springframework.stereotype.Component;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Locale;

@Component
@RequiredArgsConstructor
public class TableTopicCommand {

    private static final String ROLE_KEY = "table-topic";

    private final TableTopicService topicService;
    private final TableTopicSessionManager sessionManager;
    private final RoleService roleService;


    /**
     * Builds the Discord card shown to the user.
     */
    public EmbedBuilder buildEmbed(TableTopicSession session) {

        TableTopicQuestion question = session.getQuestion();

        EmbedBuilder embed = new EmbedBuilder();
        embed.setTitle("🗣️ Table Topic");

        StringBuilder description = new StringBuilder();

        // Badge row: `📂 Category` `🟢 Easy`
        List<String> badges = new ArrayList<>();

        String category = question.category();      // adjust if your field name differs
        if (category != null && !category.isBlank()) {
            badges.add("`📂 " + capitalize(category) + "`");
        }

        String difficulty = question.difficulty();  // adjust if your field name differs
        if (difficulty != null && !difficulty.isBlank()) {
            badges.add("`" + difficultyBadge(difficulty) + "`");
        }

        if (!badges.isEmpty()) {
            description.append(String.join(" ", badges)).append("\n\n");
        }

        description.append("**")
                .append(question.question())
                .append("**");

        if (session.getPracticeWord() != null) {
            description.append("\n\n🎲 **Random Word:** `")
                    .append(session.getPracticeWord())
                    .append("`")
                    .append("\n\n*Tip: Try to link the word to your Table Topic answer.*");
        }

        embed.setDescription(description.toString());
        return embed;
    }

    private static String difficultyBadge(String difficulty) {
        return switch (difficulty.trim().toLowerCase(Locale.ROOT)) {
            case "easy" -> "🟢 Easy";
            case "medium" -> "🟡 Medium";
            case "hard" -> "🔴 Hard";
            default -> "🎯 " + capitalize(difficulty);
        };
    }

    private static String capitalize(String s) {
        String t = s.trim();
        return t.isEmpty() ? t : t.substring(0, 1).toUpperCase(Locale.ROOT) + t.substring(1);
    }

    /**
     * Handles /topic. Called from SlashCommandListener for both
     * /topic and /practice.
     */
    public void handleTopicCommand(
            SlashCommandInteractionEvent event
    ) {

        String category = event.getOption("category") != null
                ? event.getOption("category").getAsString()
                : null;

        String difficulty = event.getOption("difficulty") != null
                ? event.getOption("difficulty").getAsString()
                : null;

        TableTopicQuestion question =
                topicService.randomQuestion(
                        category,
                        difficulty,
                        null
                );

        if (question == null) {
            event.reply(
                    "❌ I couldn't find a topic matching those filters."
            ).setEphemeral(true).queue();
            return;
        }

        TableTopicSession session =
                new TableTopicSession(
                        category,
                        difficulty,
                        question
                );

        String sessionId =
                sessionManager.createSession(session);

        event.reply("Generated by " + event.getUser().getAsMention())
                .setAllowedMentions(Collections.emptyList())
                .addEmbeds(buildEmbed(session).build())
                .addActionRow(TableTopicButtonListener.buttons(sessionId))
                .queue();

        roleService.grantRoles(event.getMember(), ROLE_KEY);
    }
}