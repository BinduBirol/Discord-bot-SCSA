package com.scsabot.discordbot.roleplay;

import com.scsabot.discordbot.dto.RolePlayScenario;
import com.scsabot.discordbot.roleplay.loader.RolePlayDataLoader;
import com.scsabot.discordbot.roleplay.loader.ThreePlayerRolePlayLoader;
import com.scsabot.discordbot.roleplay.loader.TwoPlayerRolePlayLoader;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.dv8tion.jda.api.EmbedBuilder;
import net.dv8tion.jda.api.entities.MessageEmbed;
import net.dv8tion.jda.api.entities.User;
import net.dv8tion.jda.api.events.interaction.command.SlashCommandInteractionEvent;
import net.dv8tion.jda.api.interactions.commands.OptionMapping;
import org.springframework.stereotype.Component;

import java.awt.Color;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

@Slf4j
@RequiredArgsConstructor
@Component
public class RolePlayCommand {

    private static final Color SCENE_COLOR = new Color(0x2B2D31);
    private static final Color SCRIPT_COLOR = new Color(0x5865F2);

    // Fixed per character slot: PLAYER_1, PLAYER_2, PLAYER_3
    private static final List<String> PLAYER_MARKERS = List.of("🟦", "🟩", "🟨");

    private static final int MAX_DESCRIPTION = 4000;

    private final TwoPlayerRolePlayLoader twoPlayerLoader;
    private final ThreePlayerRolePlayLoader threePlayerLoader;

    public void handleRolePlayCommand(SlashCommandInteractionEvent event) {

        List<User> players = collectPlayers(event);

        if (new HashSet<>(players).size() != players.size()) {
            replyError(event, "Each player must be a different person.");
            return;
        }
        if (players.stream().anyMatch(User::isBot)) {
            replyError(event, "Bots can't take part in a roleplay.");
            return;
        }

        RolePlayDataLoader loader =
                players.size() == 3 ? threePlayerLoader : twoPlayerLoader;

        Optional<RolePlayScenario> picked = loader.getRandom();
        if (picked.isEmpty()) {
            replyError(event, "No " + players.size() + "-player roleplays are available yet.");
            return;
        }

        RolePlayScenario scenario = picked.get();

        if (scenario.characters().size() != players.size()) {
            log.error("Scenario {} has {} characters but {} players joined",
                    scenario.id(), scenario.characters().size(), players.size());
            replyError(event, "That roleplay is misconfigured. Please try again.");
            return;
        }

        // Randomly assign users to PLAYER_1, PLAYER_2, ...
        List<User> shuffled = new ArrayList<>(players);
        Collections.shuffle(shuffled);

        Map<String, User> userByCharacter = new LinkedHashMap<>();
        for (int i = 0; i < scenario.characters().size(); i++) {
            userByCharacter.put(scenario.characters().get(i).id(), shuffled.get(i));
        }

        log.info("RolePlay {} started for {} players", scenario.id(), players.size());

        Map<String, String> markerByCharacter = buildMarkerMap(scenario);

        List<MessageEmbed> embeds = new ArrayList<>();
        embeds.add(buildSceneEmbed(scenario, userByCharacter, markerByCharacter));
        embeds.addAll(buildScriptEmbeds(scenario, userByCharacter, markerByCharacter));

        event.reply("Generated by " + event.getUser().getAsMention())
                .addEmbeds(embeds)
                .queue();
    }

    private List<User> collectPlayers(SlashCommandInteractionEvent event) {
        List<User> players = new ArrayList<>();
        for (String name : List.of("user1", "user2", "user3")) {
            OptionMapping option = event.getOption(name);
            if (option != null) {
                players.add(option.getAsUser());
            }
        }
        return players;
    }

    private Map<String, String> buildMarkerMap(RolePlayScenario scenario) {
        Map<String, String> markers = new HashMap<>();
        for (int i = 0; i < scenario.characters().size(); i++) {
            markers.put(
                    scenario.characters().get(i).id(),
                    PLAYER_MARKERS.get(i % PLAYER_MARKERS.size())
            );
        }
        return markers;
    }

    // Scene + cast legend (the square next to each player is their colour in the script)
    private MessageEmbed buildSceneEmbed(RolePlayScenario scenario,
                                         Map<String, User> userByCharacter,
                                         Map<String, String> markerByCharacter) {

        EmbedBuilder embed = new EmbedBuilder()
                .setColor(SCENE_COLOR)
                .setTitle("🎭 " + scenario.title())
                .setDescription(scenario.situation())
                .setFooter(scenario.category());

        for (RolePlayScenario.Character character : scenario.characters()) {
            User user = userByCharacter.get(character.id());
            embed.addField(
                    markerByCharacter.get(character.id()) + " "
                            + character.id().replace("_", " "),
                    user.getAsMention() + " — " + character.role()
                            + "\n🎯 " + character.goal(),
                    false
            );
        }
        return embed.build();
    }

    // One parent card, one compact line per turn
    // One parent card, each turn gets its own small block
    private List<MessageEmbed> buildScriptEmbeds(RolePlayScenario scenario,
                                                 Map<String, User> userByCharacter,
                                                 Map<String, String> markerByCharacter) {

        List<String> pages = new ArrayList<>();
        StringBuilder page = new StringBuilder();

        for (RolePlayScenario.DialogueLine line : scenario.dialogue()) {
            User speaker = userByCharacter.get(line.speaker());
            String who = speaker != null ? speaker.getAsMention() : line.speaker();
            String marker = markerByCharacter.getOrDefault(line.speaker(), "⬜");

            String body = switch (line.type()) {
                case EXACT -> "> 💬 \"" + line.text() + "\"";
                case PROMPT -> "> 🎯 *" + line.text() + "*";
            };

            String turn = "%s **%d · %s**\n%s\n\n".formatted(marker, line.step(), who, body);

            if (!page.isEmpty() && page.length() + turn.length() > MAX_DESCRIPTION) {
                pages.add(page.toString());
                page = new StringBuilder();
            }
            page.append(turn);
        }
        pages.add(page.toString().stripTrailing());

        List<MessageEmbed> embeds = new ArrayList<>();
        for (int i = 0; i < pages.size(); i++) {
            EmbedBuilder embed = new EmbedBuilder()
                    .setColor(SCRIPT_COLOR)
                    .setDescription(pages.get(i));

            if (i == 0) {
                embed.setTitle("📜 Script");
            }
            if (i == pages.size() - 1) {
                embed.setFooter("💬 Say it exactly as written  ·  🎯 Improvise using the hint");
            }
            embeds.add(embed.build());
        }
        return embeds;
    }

    private void replyError(SlashCommandInteractionEvent event, String message) {
        event.reply(message).setEphemeral(true).queue();
    }
}